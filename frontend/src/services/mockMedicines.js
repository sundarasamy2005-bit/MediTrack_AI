export const getLocalMedicines = () => {
  try {
    const saved = localStorage.getItem('medscan_local_medicines');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {}
  // Default to initial demo catalog
  try {
    localStorage.setItem('medscan_local_medicines', JSON.stringify(initialDemoMedicines));
  } catch (e) {}
  return initialDemoMedicines;
};

export const saveLocalMedicines = (medicines) => {
  try {
    localStorage.setItem('medscan_local_medicines', JSON.stringify(medicines));
  } catch (e) {}
};
